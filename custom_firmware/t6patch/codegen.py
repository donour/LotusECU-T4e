"""Generated assembly and linker scripts.

Instruction text from target.toml / module.toml (displaced instructions,
expected instructions, core-site replacements) is plain GNU as syntax.
Target symbols in it resolve at link time, so relative branches to them are
encoded correctly. `{expr}` is evaluated by t6patch first, with the target
symbols, for arithmetic the assembler cannot do on undefined symbols:

	lhz %r0, {CAL_sensor_O2_heater_threshold - CAL_base}(%r3)
"""

import ast, operator, re

HEADER = "# Generated by t6patch. Do not edit.\n"
CAL_MAGIC = b"T6PCAL01"

_OPS = {
	ast.Add: operator.add, ast.Sub: operator.sub, ast.Mult: operator.mul,
	ast.FloorDiv: operator.floordiv, ast.LShift: operator.lshift,
	ast.RShift: operator.rshift, ast.BitAnd: operator.and_, ast.BitOr: operator.or_,
	ast.USub: operator.neg,
}

def _eval(node, symbols):
	if(isinstance(node, ast.Constant) and isinstance(node.value, int)): return node.value
	if(isinstance(node, ast.Name)):
		if(node.id not in symbols): raise KeyError(node.id)
		return symbols[node.id]
	if(isinstance(node, ast.BinOp) and type(node.op) in _OPS):
		return _OPS[type(node.op)](_eval(node.left, symbols), _eval(node.right, symbols))
	if(isinstance(node, ast.UnaryOp) and type(node.op) in _OPS):
		return _OPS[type(node.op)](_eval(node.operand, symbols))
	raise ValueError(ast.dump(node))

def expand(text, symbols):
	def sub(m):
		try:
			return str(_eval(ast.parse(m[1], mode="eval").body, symbols))
		except KeyError as e:
			raise ValueError(f"'{text}': symbol {e} is not defined by the target")
		except (SyntaxError, ValueError):
			raise ValueError(f"'{text}': cannot evaluate {{{m[1]}}}")
	return re.sub(r"\{([^{}]*)\}", sub, text)

def _addr(a):
	return a if isinstance(a, str) else f"0x{a:X}"

def _reg(r):
	return r if r.startswith("%") else "%" + r

def hooks_asm(target, handlers, symbols):
	"""Dispatchers for the hooks in `handlers` ({hook name: [symbols]}) and the
	`ba` written over each hook site."""
	out = [HEADER]
	for name, funcs in handlers.items():
		hook = target.hooks[name]
		label = f"t6p_hook_{name}"
		out += ["\t.section .text.t6p_hooks,\"ax\"", f"\t.global {label}", f"{label}:"]
		frame = hook.lr_live or bool(hook.live)
		size = (8 + 4*len(hook.live) + 15) & ~15
		if(frame):
			out.append(f"\tstwu\t%r1, -{size}(%r1)")
			for i, r in enumerate(hook.live): out.append(f"\tstw\t{_reg(r)}, {8+4*i}(%r1)")
			if(hook.lr_live): out += ["\tmflr\t%r0", f"\tstw\t%r0, {size+4}(%r1)"]
		for f in funcs: out.append(f"\tbl\t{f}")
		if(frame):
			if(hook.lr_live): out += [f"\tlwz\t%r0, {size+4}(%r1)", "\tmtlr\t%r0"]
			for i, r in enumerate(hook.live): out.append(f"\tlwz\t{_reg(r)}, {8+4*i}(%r1)")
			out.append(f"\taddi\t%r1, %r1, {size}")
		out.append("\t# Displaced instruction")
		out += [f"\t{expand(i, symbols)}" for i in hook.displaced]
		if(hook.resume is not None): out.append(f"\tba\t{_addr(hook.resume)}")
		out += ["", f"\t.section .patch.hook.{name},\"ax\"", f"\tba\t{label}", ""]
	return "\n".join(out) + "\n"

def replace_asm(sites, symbols):
	"""Replacement code for core sites: [(key, [instructions])]."""
	out = [HEADER]
	for key, lines in sites:
		out.append(f"\t.section .patch.{key},\"ax\"")
		out += [f"\t{expand(l, symbols)}" for l in lines]
		out.append("")
	return "\n".join(out) + "\n"

def expect_asm(sites, symbols):
	"""Expected original instructions: [(key, [instructions])]."""
	out = [HEADER]
	for key, lines in sites:
		out.append(f"\t.section .expect.{key},\"ax\"")
		out += [f"\t{expand(l, symbols)}" for l in lines]
		out.append("")
	return "\n".join(out) + "\n"

# Module ids may contain '-' (fine in section names, not in symbols).
def cal_marker(mid):
	return "t6p_cal_mod_" + re.sub(r"[^A-Za-z0-9_]", "_", mid)

def cal_asm(cal_includes):
	"""Patch calibration block: header, then each module's CALENTRY data.
	`cal_includes` is [(module id, version, assembler path)]. The block is
	copied to RAM (CAL_base_extra) at init; modules address entries as
	OFF_<name>(CAL_base_extra)."""
	out = [HEADER,
		".macro CALENTRY symbol",
		"\t\\symbol:",
		"\t.equ OFF_\\symbol, (\\symbol-CAL_extra)",
		"\t.global \\symbol, OFF_\\symbol",
		".endm",
		"",
		"\t.section .data.t6p_cal,\"aw\"",
		"\t.balign 4",
		"\t.global CAL_extra, CAL_extra_end, CAL_extra_size",
		"CAL_extra:",
		f"\t.ascii\t\"{CAL_MAGIC.decode()}\"",
		"\t.long\t0\t\t# Layout hash, written by t6patch after linking",
		"\t.long\tCAL_extra_size",
	]
	for mid, version, path in cal_includes:
		# t6p_cal_mod_<id> marks where each module's entries start (for the report).
		mark = cal_marker(mid)
		out += [f"\t# Module {mid} v{version}", f"\t.global {mark}",
			f"{mark}:", f"\t.include \"{path}\""]
	out += [
		"\t.balign 4",
		"CAL_extra_end:",
		"\t.equ CAL_extra_size, (CAL_extra_end-CAL_extra)",
		"",
		"\t.section .bss",
		"\t.balign 4",
		"\t.global CAL_base_extra",
		"CAL_base_extra:",
		"\t.skip\tCAL_extra_size",
	]
	return "\n".join(out) + "\n"

def linker_script(layout, site_addrs, sym_file, cal_site_addrs=None):
	"""Main link: new code in free prog flash, the cal block in free cal
	flash, variables in free RAM, each .patch.<key> section at its site and
	each .calsite.<key> section (a module's defaults for a stock-cal location)
	at its cal flash address."""
	out = [
		"/* Generated by t6patch. Do not edit. */",
		f"INCLUDE {sym_file}",
		"",
		"SECTIONS",
		"{",
		f"\t.text 0x{layout.rom:X} : {{",
		"\t\tKEEP(*(.text.t6p_hooks))",
		"\t\t*(.text .text.*)",
		"\t\t*(.rodata .rodata.*)",
		"\t}",
		f"\t.data 0x{layout.cal:X} : {{",
		"\t\tt6p_cal_start = .;",
		"\t\tKEEP(*(.data.t6p_cal))",
		"\t\t*(.data .data.*)",
		"\t\tt6p_cal_end = .;",
		"\t}",
		f"\t.bss 0x{layout.ram:X} (NOLOAD) : {{",
		"\t\t__patch_bss_start = .;",
		"\t\t*(.bss .bss.* .sbss .sbss.* .scommon COMMON)",
		"\t\t__patch_bss_end = .;",
		"\t\t. = ALIGN(16);",
		"\t\t__patch_ram_end = .;",
		"\t}",
	]
	for key, addr in site_addrs.items():
		out.append(f"\t.patch.{key} 0x{addr:X} : {{ KEEP(*(.patch.{key})) }}")
	for key, addr in (cal_site_addrs or {}).items():
		out.append(f"\t.calsite.{key} 0x{addr:X} : {{ KEEP(*(.calsite.{key})) }}")
	out += [
		"\t/DISCARD/ : { *(.comment) *(.note .note.*) *(.gnu.attributes) *(.eh_frame) }",
		"}",
		"",
		f"ASSERT(ADDR(.text) + SIZEOF(.text) <= 0x{layout.rom_end:X}, \"patch code does not fit in prog flash\")",
		f"ASSERT(t6p_cal_end <= 0x{layout.cal_end:X}, \"patch calibration does not fit in cal flash\")",
		f"ASSERT(__patch_ram_end <= 0x{layout.ram_end:X}, \"patch RAM is over the target budget\")",
	]
	return "\n".join(out) + "\n"

def expect_linker_script(site_addrs, sym_file):
	out = ["/* Generated by t6patch. Do not edit. */", f"INCLUDE {sym_file}", "", "SECTIONS", "{"]
	for key, addr in site_addrs.items():
		out.append(f"\t.expect.{key} 0x{addr:X} : {{ KEEP(*(.expect.{key})) }}")
	out += ["\t/DISCARD/ : { *(.text) *(.data) *(.bss) *(.comment) *(.note .note.*) *(.gnu.attributes) }", "}"]
	return "\n".join(out) + "\n"
